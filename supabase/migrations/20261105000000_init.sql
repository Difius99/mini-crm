create type public.user_role as enum ('manager', 'executor');
create type public.task_status as enum ('new', 'in_progress', 'review', 'accepted', 'rework');

create table public.profiles (
  id        uuid primary key references auth.users(id) on update cascade on delete cascade,
  full_name text not null,
  role      public.user_role not null default 'executor'
);

create table public.objects (
  id         uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  name       text not null,
  address    text not null
);

create table public.tasks (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  title       text not null,
  description text,
  object_id   uuid not null,
  assignee_id uuid not null,
  author_id   uuid not null default auth.uid(),
  status      public.task_status not null default 'new',

  constraint tasks_object_id_fkey   foreign key (object_id)   references public.objects(id)  on update cascade on delete cascade,
  constraint tasks_assignee_id_fkey foreign key (assignee_id) references public.profiles(id) on update cascade on delete no action,
  constraint tasks_author_id_fkey   foreign key (author_id)   references public.profiles(id) on update cascade on delete no action
);
create index tasks_object_id_idx   on public.tasks(object_id);
create index tasks_assignee_id_idx on public.tasks(assignee_id);

create table public.task_history (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  task_id     uuid not null,
  from_status public.task_status,
  to_status   public.task_status not null,
  changed_by  uuid not null,
  comment     text,

  constraint task_history_task_id_fkey    foreign key (task_id)    references public.tasks(id)    on update cascade on delete cascade,
  constraint task_history_changed_by_fkey foreign key (changed_by) references public.profiles(id) on update cascade on delete no action
);
create index task_history_task_id_idx on public.task_history(task_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', new.email))
  on conflict (id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_manager()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'manager'
  );
$$;

create or replace function public.tasks_guard()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if current_user in ('authenticated', 'anon') then
    if tg_op = 'INSERT' then
      if new.status <> 'new' then
        raise exception 'Задача создаётся только в статусе «Новая»';
      end if;
      if new.author_id is distinct from auth.uid() then
        raise exception 'Автором может быть только текущий пользователь';
      end if;
    else
      if new.status <> old.status then
        raise exception 'Статус меняется только через change_task_status';
      end if;
      if new.author_id <> old.author_id or new.created_at <> old.created_at then
        raise exception 'Автора и дату создания менять нельзя';
      end if;
    end if;
  end if;

  if not exists (select 1 from public.profiles
                 where id = new.assignee_id and role = 'executor') then
    raise exception 'Исполнитель должен иметь роль «исполнитель»';
  end if;

  return new;
end $$;

create trigger tasks_guard
  before insert or update on public.tasks
  for each row execute function public.tasks_guard();

create or replace function public.log_task_created()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.task_history (task_id, from_status, to_status, changed_by)
  values (new.id, null, 'new', new.author_id);
  return new;
end $$;

create trigger tasks_log_created
  after insert on public.tasks
  for each row execute function public.log_task_created();

create or replace function public.change_task_status(
  p_task_id uuid,
  p_to      public.task_status,
  p_comment text default null
)
returns public.tasks
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid        uuid    := auth.uid();
  v_is_manager boolean := public.is_manager();
  v_comment    text    := nullif(trim(coalesce(p_comment, '')), '');
  v_task       public.tasks;
  v_from       public.task_status;
  v_allowed    boolean;
begin
  if v_uid is null then
    raise exception 'Требуется вход в систему';
  end if;

  select * into v_task from public.tasks where id = p_task_id for update;

  if not found or (not v_is_manager and v_task.assignee_id <> v_uid) then
    raise exception 'Задача не найдена';
  end if;

  v_from := v_task.status;

  v_allowed := case
    when v_is_manager then
         (v_from = 'review'      and p_to = 'accepted')
      or (v_from = 'review'      and p_to = 'rework')
    else
         (v_from = 'new'         and p_to = 'in_progress')
      or (v_from = 'in_progress' and p_to = 'review')
      or (v_from = 'rework'      and p_to = 'in_progress')
  end;

  if not v_allowed then
    raise exception 'Недопустимый переход: % → %', v_from, p_to;
  end if;

  if p_to = 'rework' and v_comment is null then
    raise exception 'Для возврата на доработку нужен комментарий';
  end if;

  update public.tasks set status = p_to where id = p_task_id returning * into v_task;

  insert into public.task_history (task_id, from_status, to_status, changed_by, comment)
  values (p_task_id, v_from, p_to, v_uid, v_comment);

  return v_task;
end $$;

revoke all on function public.change_task_status(uuid, public.task_status, text) from public, anon;
grant execute on function public.change_task_status(uuid, public.task_status, text) to authenticated;

alter table public.profiles     enable row level security;
alter table public.objects      enable row level security;
alter table public.tasks        enable row level security;
alter table public.task_history enable row level security;

create policy profiles_select on public.profiles
  for select to authenticated
  using (true);

create policy objects_select on public.objects
  for select to authenticated
  using (
    public.is_manager()
    or exists (
      select 1 from public.tasks t
      where t.object_id = objects.id and t.assignee_id = auth.uid()
    )
  );
create policy objects_insert on public.objects
  for insert to authenticated with check (public.is_manager());
create policy objects_update on public.objects
  for update to authenticated using (public.is_manager()) with check (public.is_manager());
create policy objects_delete on public.objects
  for delete to authenticated using (public.is_manager());

create policy tasks_select on public.tasks
  for select to authenticated
  using (public.is_manager() or assignee_id = auth.uid());
create policy tasks_insert on public.tasks
  for insert to authenticated with check (public.is_manager());
create policy tasks_update on public.tasks
  for update to authenticated using (public.is_manager()) with check (public.is_manager());
create policy tasks_delete on public.tasks
  for delete to authenticated using (public.is_manager());

create policy task_history_select on public.task_history
  for select to authenticated
  using (exists (select 1 from public.tasks t where t.id = task_history.task_id));

revoke all on public.profiles, public.objects, public.tasks, public.task_history from anon;
revoke insert, update, delete, truncate on public.task_history from authenticated;
revoke insert, update, delete, truncate on public.profiles     from authenticated;
revoke truncate on public.objects, public.tasks from authenticated;
grant select on public.profiles, public.task_history to authenticated;
grant select, insert, update, delete on public.objects, public.tasks to authenticated;
